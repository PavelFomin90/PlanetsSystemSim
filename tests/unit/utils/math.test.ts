import { toRadians, toDegrees, round } from "../../../src/utils/math";

// Тесты для утилит преобразования углов и округления
describe("Math Utilities", () => {
  describe("toRadians", () => {
    it("должен конвертировать 0 градусов в 0 радиан", () => {
      expect(toRadians(0)).toBe(0);
    });

    it("должен конвертировать 180 градусов в PI радиан", () => {
      expect(toRadians(180)).toBe(Math.PI);
    });

    it("должен конвертировать 90 градусов в PI/2 радиан", () => {
      expect(toRadians(90)).toBe(Math.PI / 2);
    });

    it("должен конвертировать 360 градусов в 2PI радиан", () => {
      expect(toRadians(360)).toBe(2 * Math.PI);
    });

    it("должен конвертировать отрицательные углы", () => {
      expect(toRadians(-180)).toBe(-Math.PI);
    });
  });

  describe("toDegrees", () => {
    it("должен конвертировать 0 радиан в 0 градусов", () => {
      expect(toDegrees(0)).toBe(0);
    });

    it("должен конвертировать PI радиан в 180 градусов", () => {
      expect(toDegrees(Math.PI)).toBe(180);
    });

    it("должен конвертировать PI/2 радиан в 90 градусов", () => {
      expect(toDegrees(Math.PI / 2)).toBe(90);
    });

    it("должен конвертировать 2PI радиан в 360 градусов", () => {
      expect(toDegrees(2 * Math.PI)).toBe(360);
    });

    it("должен конвертировать отрицательные радианы", () => {
      expect(toDegrees(-Math.PI)).toBe(-180);
    });
  });

  describe("round", () => {
    it("должен округлять число до 4 знаков после запятой по умолчанию", () => {
      expect(round(3.1415926535)).toBe(3.1416);
    });

    it("должен округлять целые числа", () => {
      expect(round(42)).toBe(42);
    });

    it("должен округлять отрицательные числа", () => {
      expect(round(-3.1415926535)).toBe(-3.1416);
    });

    it("должен округлять до указанного количества знаков", () => {
      expect(round(3.1415926535, 2)).toBe(3.14);
      expect(round(3.1415926535, 3)).toBe(3.142);
      expect(round(3.1415926535, 0)).toBe(3);
    });

    it("должен обрабатывать числа, которые не требуют округления", () => {
      expect(round(2.5, 1)).toBe(2.5);
    });

    it("должен правильно округлять при переходе через разряд", () => {
      expect(round(1.99999)).toBe(2);
      expect(round(0.99999)).toBe(1);
    });
  });
});
